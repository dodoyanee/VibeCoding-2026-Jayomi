/* =====================================================
   common.js : 모든 페이지 공통 기능 - 햄버거 메뉴 열기/닫기
   ===================================================== */

// 즉시실행함수로 감싸 다른 js파일과 변수명이 겹치지 않게 함
(() => {
  // 1. 대상 선정
  // 1-1. 이벤트 대상 : 햄버거 버튼 (.menu-btn)
  const 햄버거 = document.querySelector(".menu-btn");
  // 1-2. 변경 대상 : 상단영역(.top-area)
  const 상단박스 = document.querySelector(".top-area");

  // 해당 요소가 없는 페이지에서는 실행하지 않음
  if (!햄버거 || !상단박스) return;

  // 2. 이벤트 함수 만들기
  // 햄버거 클릭시 상단 박스에 클래스(.on) 넣기/빼기
  햄버거.onclick = () => {
    // classList : add(넣기) / remove(빼기) / toggle(넣기·빼기 전환)
    상단박스.classList.toggle("on");
  };
})();
