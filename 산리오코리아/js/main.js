// =====================================================
// place 영역 배경 슬라이드 (바닐라JS)
// - 처음엔 1번 이미지가 보이고, 2초 후 1초간 다음 이미지가 오른쪽에서 들어옴
// - 맨 앞 박스를 이동이 끝나면 맨 뒤로 보내서 3장이 무한 반복됨
// =====================================================

/* ★ 대상 : 이미지박스 3개를 담은 트랙
(() = > {코드}() - > 변수명 중복 위험을 없애준다!
이 구역은 바로 실행됨! 중괄호안이 지역변수가 됨!
전역변수는 함수 바깥에 있는 변수
지역변수는 함수 내부에 있는 변수 */

/* (()=>{

    내코드...
 
   })(); */

(()=>{
  const 슬라이드트랙 = document.querySelector('.place-track');

  if (슬라이드트랙) {
    const 대기시간 = 2000; // 멈춰있는 시간 2초
    const 이동시간 = 1000; // 이동 애니메이션 1초

    // 한 장 넘기기
    const 다음장 = () => {
      // 1. 트랙을 왼쪽으로 100% 이동 → 다음 박스가 오른쪽에서 들어옴
      슬라이드트랙.style.transition = `transform ${이동시간}ms ease-in-out`;
      슬라이드트랙.style.transform = 'translateX(-100%)';

      // 2. 이동이 끝나면 맨 앞 박스를 맨 뒤로 보내고 위치를 즉시 원위치(0)
      setTimeout(() => {
        슬라이드트랙.style.transition = 'none';
        슬라이드트랙.appendChild(슬라이드트랙.firstElementChild);
        슬라이드트랙.style.transform = 'translateX(0)';
        // 트랜지션 없이 적용되도록 강제 리플로우
        슬라이드트랙.offsetWidth;

        // 3. 2초 쉬었다가 다시 반복
        setTimeout(다음장, 대기시간);
      }, 이동시간);
    }; ///////// 다음장 /////////

    // 처음엔 2초 후 시작
    setTimeout(다음장, 대기시간);
  } ///////// if /////////
})();